"""Architecture loader for CGRA-ME MRRG files."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Callable, Dict, Optional
from pathlib import Path

from cgrasolve.graph.mrrg import MRRG


@dataclass
class ArchitectureBundle:
    """Typed return object for directory-based architecture loading."""

    mrrg: MRRG
    compiler_arch: Dict[str, Any]


class ArchitectureLoader:
    """
    Loader for CGRA architectures from CGRA-ME MRRG format.

    This class provides an interface to load MRRG files generated by CGRA-ME
    and convert them into FastMap's internal MRRG representation.
    """

    def __init__(self, *, enable_select: bool = False) -> None:
        """Initialize the architecture loader.

        Args:
            enable_select: When True, the dora MRRG parser promotes phi_mux_inst
                FUs (`optype: PHI`) to NodeType.FUNCTION with SELECT support.
                Required when mapping kernels that contain `select` ops; off by
                default to keep placer behavior identical to ALU-only flows.
        """
        self.supported_formats = ['xml', 'json', 'dot']
        self.enable_select = enable_select

    def load_from_directory(self, dir_path: str) -> ArchitectureBundle:
        """Load an architecture from a directory containing mrrg.json and compiler_arch.json.

        This is the canonical public API for loading benchmark architectures.

        Args:
            dir_path: Path to the architecture directory.

        Returns:
            ArchitectureBundle with mrrg and compiler_arch fields.

        Raises:
            FileNotFoundError: If mrrg.json or compiler_arch.json is missing.
            ValueError: If JSON is invalid, schema validation fails, or
                        MRRG II does not match compiler_arch fabric_contexts.
        """
        from cgrasolve.architecture.compiler_arch import load_and_validate_compiler_arch

        d = Path(dir_path)

        mrrg_path = d / "mrrg.json"
        compiler_arch_path = d / "compiler_arch.json"

        if not mrrg_path.exists():
            raise FileNotFoundError(f"mrrg.json not found in {dir_path}")
        if not compiler_arch_path.exists():
            raise FileNotFoundError(f"compiler_arch.json not found in {dir_path}")

        mrrg = self._load_from_json(mrrg_path)
        compiler_arch = load_and_validate_compiler_arch(str(compiler_arch_path))

        if mrrg.II != compiler_arch["fabric_contexts"]:
            raise ValueError(
                f"MRRG II ({mrrg.II}) does not match "
                f"compiler_arch fabric_contexts ({compiler_arch['fabric_contexts']})"
            )

        return ArchitectureBundle(mrrg=mrrg, compiler_arch=compiler_arch)

    def resolve_directory_for_ii(self, path: str, ii: int) -> Path:
        """Resolve the architecture directory that corresponds to ``ii``."""
        candidate = Path(path)
        if candidate.is_file():
            candidate = candidate.parent

        ii_dir = f"II_{ii}"

        if candidate.name == ii_dir:
            return candidate

        child = candidate / ii_dir
        if child.is_dir():
            return child

        parent_child = candidate.parent / ii_dir
        if parent_child.is_dir():
            return parent_child

        raise FileNotFoundError(
            f"Could not resolve architecture directory for II={ii} from {path}"
        )

    def load_bundle_for_ii(self, path: str, ii: int) -> ArchitectureBundle:
        """Load the architecture bundle for a specific II directory."""
        ii_dir = self.resolve_directory_for_ii(path, ii)
        return self.load_from_directory(str(ii_dir))

    def make_mrrg_loader(self, path: str) -> Callable[[int], MRRG]:
        """Return a callable that loads an MRRG for the requested II."""
        def _loader(ii: int) -> MRRG:
            return self.load_bundle_for_ii(path, ii).mrrg

        return _loader

    def load_from_file(self, file_path: str) -> Optional[MRRG]:
        """
        Load an MRRG from a file.

        Args:
            file_path: Path to the MRRG file

        Returns:
            MRRG object, or None if loading fails

        Raises:
            FileNotFoundError: If the file doesn't exist
            ValueError: If the file format is unsupported
        """
        path = Path(file_path)

        if not path.exists():
            raise FileNotFoundError(f"File not found: {file_path}")

        suffix = path.suffix.lstrip('.')

        if suffix not in self.supported_formats:
            raise ValueError(
                f"Unsupported file format: {suffix}. "
                f"Supported formats: {', '.join(self.supported_formats)}"
            )

        # Dispatch to appropriate parser
        if suffix == 'xml':
            return self._load_from_xml(path)
        elif suffix == 'json':
            return self._load_from_json(path)
        elif suffix == 'dot':
            return self._load_from_dot(path)

        return None

